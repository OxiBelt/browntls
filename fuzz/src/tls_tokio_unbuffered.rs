const MAX_OPS: usize = 128;
const MAX_CONNECTIONS: usize = 3;

/// Each operation is followed by a byte whose low bit is the side (or the
/// lane that side writes to), then by its arguments.
#[derive(Clone, Copy)]
#[repr(u8)]
enum Op {
    /// Polls that side's handshake future once.
    Poll,
    /// `flags, data`: one write; bit 0 of the flags makes it vectored, bit 1
    /// takes a length (u16, plus 65 536 with bit 2) of generated bytes
    /// instead of a short field.
    Write,
    /// `flags, size`: one read; bit 0 through `poll_fill_buf`, bit 1
    /// multiplies the size by 256.
    Read,
    /// One flush.
    Flush,
    /// One shutdown.
    Shutdown,
    /// Polls everything until nothing moves; bits 0 and 1 of the byte make
    /// the client's and the server's reads `poll_fill_buf`.
    Pump,
    /// `refresh_traffic_keys`.
    KeyUpdate,
    /// Every accessor of that side's future or stream.
    Accessors,
    /// The server's accepted 0-RTT data is taken out.
    TakeEarlyData,
    /// The stream is taken apart (`into_parts`) and its connection driven
    /// by hand from then on.
    IntoParts,
    /// The lazy acceptor gives its transport back.
    TakeIo,
    /// The server asks for a certificate after the handshake.
    RequestAuth,
    /// `settings (4 bytes)`: changes a lane's chunking, masks and capacity.
    Throttle,
    /// `position (u16), xor`: flips bits of a byte in flight.
    Damage,
    /// `times, bytes (short field)`: appends raw bytes to a lane, up to 32
    /// times.
    Inject,
    /// `kind`: ends a lane, or makes its writes take nothing, its writes
    /// fail or its reads fail.
    Break,
    /// `client mode, server mode`: a new connection with the same
    /// configurations.
    Reconnect,
}

const OPS: [Op; 17] = [
    Op::Poll,
    Op::Write,
    Op::Read,
    Op::Flush,
    Op::Shutdown,
    Op::Pump,
    Op::KeyUpdate,
    Op::Accessors,
    Op::TakeEarlyData,
    Op::IntoParts,
    Op::TakeIo,
    Op::RequestAuth,
    Op::Throttle,
    Op::Damage,
    Op::Inject,
    Op::Break,
    Op::Reconnect,
];

/// The bytes a generated write carries.
fn pattern(len: usize, salt: u8) -> Vec<u8> {
    (0..len)
        .map(|i| (i as u8).wrapping_mul(31).wrapping_add((i >> 8) as u8) ^ salt)
        .collect()
}

pub fn run(data: &[u8]) {
    if let Some(mut world) = play(data) {
        world.finish();
    }
}

/// Runs the input's operations, leaving the world as they left it.
fn play(data: &[u8]) -> Option<World> {
    crate::init();
    let mut input = Input::new(data);
    let knobs = Knobs::read(&mut input);
    let mode = input.array::<2>();
    let transport = input.array::<8>();
    let mut world = World::new(knobs, mode, transport)?;
    let mut connections = 1;

    for _ in 0..MAX_OPS {
        if input.is_empty() {
            break;
        }
        let op = *input.pick(&OPS);
        let arg = input.byte();
        let side = usize::from(arg & 1);
        match op {
            Op::Poll => world.poll_handshake(side),
            Op::Write => {
                let flags = input.byte();
                let generated;
                let data = if flags & 2 == 0 {
                    input.short_field()
                } else {
                    let extra = usize::from(flags & 4) << 14;
                    generated = pattern(usize::from(input.u16()) + extra, flags);
                    &generated[..]
                };
                world.write(side, flags & 1 != 0, data);
            }
            Op::Read => {
                let flags = input.byte();
                let size = usize::from(input.byte()) << ((flags & 2) * 4);
                world.read(side, flags & 1 != 0, size);
            }
            Op::Flush => drop(world.flush(side, false)),
            Op::Shutdown => drop(world.flush(side, true)),
            Op::Pump => world.pump(arg),
            Op::KeyUpdate => world.key_update(side),
            Op::Accessors => world.accessors(side),
            Op::TakeEarlyData => world.take_early_data(),
            Op::IntoParts => world.take_apart(side),
            Op::TakeIo => world.take_io(),
            Op::RequestAuth => world.request_client_auth(),
            Op::Throttle => {
                let settings = input.array::<4>();
                world.wire.borrow_mut().lanes[side].configure(settings);
            }
            Op::Damage => {
                let position = usize::from(input.u16());
                let xor = input.byte().max(1);
                let mut wire = world.wire.borrow_mut();
                let lane = &mut wire.lanes[side];
                if !lane.bytes.is_empty() {
                    let i = position % lane.bytes.len();
                    lane.bytes[i] ^= xor;
                    world.disturbed = true;
                }
            }
            Op::Inject => {
                let times = 1 + input.byte() % 32;
                let bytes = input.short_field();
                let mut wire = world.wire.borrow_mut();
                for _ in 0..times {
                    if !bytes.is_empty() && wire.lanes[side].push(bytes) {
                        world.disturbed = true;
                    }
                }
            }
            Op::Break => {
                let kind = input.byte() % 4;
                let mut wire = world.wire.borrow_mut();
                let lane = &mut wire.lanes[side];
                match kind {
                    0 => lane.closed = true,
                    1 => lane.fail(Fault::WriteZero),
                    2 => lane.fail(Fault::WriteError),
                    _ => lane.fail(Fault::ReadError),
                }
                world.disturbed = true;
            }
            Op::Reconnect => {
                let mode = input.array::<2>();
                if connections < MAX_CONNECTIONS {
                    connections += 1;
                    world.finish();
                    world.connect(mode);
                }
            }
        }
    }
    Some(world)
}

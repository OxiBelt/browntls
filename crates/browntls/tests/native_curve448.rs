/// An X448 group whose own share is replaced by `share(real_share)`.
#[derive(Debug)]
struct MalformedX448 {
    what: &'static str,
    share: fn(&[u8]) -> Vec<u8>,
}

struct MalformedKx {
    inner: Box<dyn ActiveKeyExchange>,
    share: Vec<u8>,
}

impl SupportedKxGroup for MalformedX448 {
    fn start(&self) -> Result<Box<dyn ActiveKeyExchange>, Error> {
        let inner = x448().start()?;
        let share = (self.share)(inner.pub_key());
        Ok(Box::new(MalformedKx { inner, share }))
    }

    fn name(&self) -> NamedGroup {
        NamedGroup::X448
    }
}

impl ActiveKeyExchange for MalformedKx {
    fn complete(self: Box<Self>, peer_pub_key: &[u8]) -> Result<SharedSecret, Error> {
        self.inner.complete(peer_pub_key)
    }

    fn pub_key(&self) -> &[u8] {
        &self.share
    }

    fn group(&self) -> NamedGroup {
        NamedGroup::X448
    }
}

/// Shares a correct X448 implementation must reject: wrong lengths, and
/// small-order u-coordinates (0, 1, -1 and the non-canonical p, p + 1) that
/// give an all-zero shared secret (RFC 9846 §7.4.2, RFC 8422 §5.11).
static MALFORMED: [MalformedX448; 9] = [
    MalformedX448 {
        what: "55 bytes",
        share: |s| s[..55].to_vec(),
    },
    MalformedX448 {
        what: "57 bytes",
        share: |s| [s, &[0]].concat(),
    },
    MalformedX448 {
        what: "32 bytes (an X25519 share)",
        share: |s| s[..32].to_vec(),
    },
    MalformedX448 {
        what: "1 byte",
        share: |s| s[..1].to_vec(),
    },
    MalformedX448 {
        what: "u = 0",
        share: |_| vec![0; 56],
    },
    MalformedX448 {
        what: "u = 1",
        share: |_| {
            let mut u = vec![0; 56];
            u[0] = 1;
            u
        },
    },
    MalformedX448 {
        what: "u = -1",
        share: |_| {
            let mut u = vec![0xff; 56];
            u[0] = 0xfe;
            u[28] = 0xfe;
            u
        },
    },
    MalformedX448 {
        what: "u = p",
        share: |_| {
            let mut u = vec![0xff; 56];
            u[28] = 0xfe;
            u
        },
    },
    MalformedX448 {
        what: "u = p + 1",
        share: |_| {
            let mut u = vec![0; 56];
            u[28..].fill(0xff);
            u
        },
    },
];

#[test]
fn malformed_x448_shares_are_rejected() {
    init_logging();
    let chain = server_chain(KeyType::EcdsaP256);
    let invalid = Error::PeerMisbehaved(PeerMisbehaved::InvalidKeyShare);
    for bad in &MALFORMED {
        let malformed: &'static dyn SupportedKxGroup = bad;
        for v in VERSIONS {
            // A malformed client share: the server rejects it.
            let client = client_for(
                v,
                provider_with_groups(&[malformed]),
                PinnedServerVerifier::new(&chain),
            )
            .with_no_client_auth();
            let server = ServerConfig::builder_with_provider(provider_with_groups(&[x448()]))
                .with_safe_default_protocol_versions()
                .unwrap()
                .with_no_client_auth()
                .with_single_cert(chain.cert_chain(), chain.private_key())
                .unwrap();
            let (mut client, mut server) = connect(client, server);
            let (client_res, server_res) = do_handshake_until_error(&mut client, &mut server);
            assert_eq!(
                server_res,
                Err(invalid.clone()),
                "{} {v:?} client share",
                bad.what
            );
            assert!(client_res.is_err(), "{} {v:?}", bad.what);

            // A malformed server share: the client rejects it.
            let client = client_for(
                v,
                provider_with_groups(&[x448()]),
                PinnedServerVerifier::new(&chain),
            )
            .with_no_client_auth();
            let server = ServerConfig::builder_with_provider(provider_with_groups(&[malformed]))
                .with_safe_default_protocol_versions()
                .unwrap()
                .with_no_client_auth()
                .with_single_cert(chain.cert_chain(), chain.private_key())
                .unwrap();
            let (mut client, mut server) = connect(client, server);
            let (client_res, _) = do_handshake_until_error(&mut client, &mut server);
            assert_eq!(
                client_res,
                Err(invalid.clone()),
                "{} {v:?} server share",
                bad.what
            );
        }
    }
}


//! Curve448: X448 key agreement (RFC 7748) and Ed448 signatures
//! (RFC 8032 §5.2).
//!
//! Layout:
//!
//! * `field` — GF(2^448 - 2^224 - 1), portable eight 56-bit limbs with
//!   64x64->128-bit products and Karatsuba multiplication on the two halves
//!   of the Goldilocks prime (constant time; limb bounds documented there).
//! * `scalar` — arithmetic modulo the group order `L` (Montgomery form,
//!   `R = 2^448`).
//! * `edwards` — the edwards448 group in projective coordinates with the
//!   complete formulas of RFC 8032 §5.2.4: a constant-time fixed-base comb
//!   and variable-time double-scalar multiplication for verification.
//! * `table` — precomputed multiples of the base point, generated by the
//!   ignored unit test `edwards::tests::regenerate_tables`; the test
//!   `tables_are_reproducible` recomputes the whole file from the base
//!   point, so a stale or corrupted table fails.
//! * [`x448`] and [`ed448`] — the public APIs. X448 public keys use the comb
//!   through the 4-isogeny between the two curves; shared secrets use a
//!   Montgomery ladder.
//!
//! There is one portable implementation and no architecture backend: the
//! reduced-radix arithmetic has no carry chains for `adcx`/`adox` to
//! shorten, and the equivalent BMI2/ADX ladder of X25519 measures no faster
//! than its portable code (see `docs/Performance.md`). X448 and Ed448 are
//! optional, non-preferred algorithms in browntls.


#[test]
fn x448_handshakes_in_tls13_and_tls12() {
    init_logging();
    for key_type in [KeyType::Ed25519, KeyType::EcdsaP256, KeyType::Rsa2048] {
        let chain = server_chain(key_type);
        for v in VERSIONS {
            let client = client_for(
                v,
                provider_with_groups(&[x448()]),
                PinnedServerVerifier::new(&chain),
            )
            .with_no_client_auth();
            let server = ServerConfig::builder_with_provider(provider_with_groups(&[x448()]))
                .with_safe_default_protocol_versions()
                .unwrap()
                .with_no_client_auth()
                .with_single_cert(chain.cert_chain(), chain.private_key())
                .unwrap();
            let (mut client, mut server) = connect(client, server);
            do_handshake(&mut client, &mut server)
                .unwrap_or_else(|e| panic!("{key_type:?} {v:?}: {e}"));
            assert_eq!(client.protocol_version(), Some(v));
            for group in [
                client.negotiated_key_exchange_group(),
                server.negotiated_key_exchange_group(),
            ] {
                assert_eq!(
                    group.unwrap().name(),
                    NamedGroup::X448,
                    "{key_type:?} {v:?}"
                );
            }
            round_trip(&mut client, &mut server);
        }
    }
}

#[test]
fn x448_is_offered_last_and_reached_through_hello_retry() {
    init_logging();
    let chain = server_chain(KeyType::EcdsaP256);
    // In the default list X448 opens the optional tier: it follows every
    // other group except the finite-field groups.
    let names: Vec<_> = prov::DEFAULT_KX_GROUPS.iter().map(|g| g.name()).collect();
    let x448_pos = names.iter().position(|n| *n == NamedGroup::X448).unwrap();
    assert!(
        names[x448_pos + 1..]
            .iter()
            .all(|n| n.key_exchange_algorithm() == KeyExchangeAlgorithm::DHE),
        "{names:?}"
    );
    // A default client against a server that only has X448: TLS 1.3 needs a
    // HelloRetryRequest (the client's key share is for its first group).
    let client = client_for(
        ProtocolVersion::TLSv1_3,
        provider(),
        PinnedServerVerifier::new(&chain),
    )
    .with_no_client_auth();
    let server = ServerConfig::builder_with_provider(provider_with_groups(&[x448()]))
        .with_safe_default_protocol_versions()
        .unwrap()
        .with_no_client_auth()
        .with_single_cert(chain.cert_chain(), chain.private_key())
        .unwrap();
    let (mut client, mut server) = connect(client, server);
    do_handshake(&mut client, &mut server).unwrap();
    assert_eq!(
        client.handshake_kind(),
        Some(browntls::HandshakeKind::FullWithHelloRetryRequest)
    );
    assert_eq!(
        client.negotiated_key_exchange_group().unwrap().name(),
        NamedGroup::X448
    );
    round_trip(&mut client, &mut server);

    // With both sides on the defaults, an earlier group wins.
    let (mut client, mut server) = connect(
        client_for(
            ProtocolVersion::TLSv1_3,
            provider(),
            PinnedServerVerifier::new(&chain),
        )
        .with_no_client_auth(),
        server_config(&chain),
    );
    do_handshake(&mut client, &mut server).unwrap();
    assert_ne!(
        client.negotiated_key_exchange_group().unwrap().name(),
        NamedGroup::X448
    );
}


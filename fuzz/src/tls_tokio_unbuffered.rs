//! `browntls_tokio::unbuffered`: the streams over the unbuffered connection
//! API, their connector, acceptor and lazy acceptor, between a genuine
//! client and server in the same process, over an in-memory transport whose
//! behaviour the input controls. One end is always unbuffered; the other
//! may be a stream of the crate root.
//!
//! Input: the 5-byte configuration header of `tls_conn`
//! (`tls_conn::setup::Knobs`), a mode byte per side, four bytes per
//! direction for the transport (largest chunk per call, masks of the reads
//! and of the writes and flushes that return `Pending`, capacity), then up
//! to 128 operations ([`Op`]).
//!
//! Client mode: bits 0-1 the entry point (`connect`, `connect_with`,
//! `with_alpn` and either), bit 2 the fallible future, bit 3 the buffered
//! connector of the crate root instead, bit 4 its 0-RTT, bit 5 the stream
//! ends through `into_parts`. Server mode: bits 0-2 `accept`,
//! `accept_with`, the lazy acceptor with `into_stream`, the lazy acceptor
//! with `into_parts`, `from_parts` and `into_stream_with`, the buffered
//! acceptor of the crate root, or a ClientHello the harness reads itself
//! for `from_parts`; bit 3 the fallible future, bit 4 a lazily chosen
//! configuration for other protocol versions, bit 5 as for the client.
//! Bit 6 of the first server mode replaces the configurations by TLS 1.3
//! ones whose record protection is the identity transform
//! (`connection.rs`): records the input writes on the wire are then
//! accepted once keys exist (key updates, alerts, data), so the checks
//! that compare what was read with what was written stop at the first
//! such write.
//!
//! The futures and streams are polled with a no-op waker, one poll per
//! operation: the harness drives them itself rather than waiting for
//! wake-ups, so it checks what polls return, not when tasks are woken.
//!
//! Checked properties (`model.rs`):
//! * plaintext a side reads (and accepted 0-RTT data) is a prefix of what
//!   the peer wrote, whatever happened to the bytes; a stream that ends
//!   (the peer's `close_notify`) delivered all of it;
//! * a write takes what the documentation says (65 536 bytes at most, one
//!   record's worth of several small slices), and nothing after shutdown;
//! * what a stream holds stays within bounds (`Debug` shows the lengths);
//! * a failed read stays failed, and after a TLS failure writes fail too;
//!   the end of a stream stays the end;
//! * on a connection the input did not disturb, no stream operation fails,
//!   and once nothing moves any more (the transport then only waits for
//!   bytes or room) the handshake is complete, nothing is left on the wire
//!   or unwritten, and both sides read everything, also through a
//!   connection taken out of its stream with `into_parts`;
//! * both sides derive the same exporter value;
//! * nothing panics, and no poll or pump loops forever.


//! Curve448 in TLS, native to native: the X448 key exchange group in TLS 1.3
//! and TLS 1.2 ECDHE, and Ed448 certificates for server and client
//! authentication.
//!
//! Neither rcgen nor rustls/ring supports Ed448, so the certificate chains
//! here are built at run time with `browntls_crypto::der::Writer` and signed
//! by the native provider's Ed448 signing key; the web-PKI verifiers then
//! validate them through `browntls-pki`. Keys exist only in memory.
//!
//! Negative cases: X448 shares of the wrong length and small-order shares
//! (all-zero shared secret) in both directions and both versions, tampered
//! Ed448 handshake signatures, a tampered Ed448 certificate signature, and a
//! peer that does not offer `ed448`.


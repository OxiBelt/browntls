//! Seeds of `tls_tokio_unbuffered`: together they reach every public
//! function of `browntls_tokio::unbuffered`.

use super::Op;
use super::world::{CLIENT, SERVER};
use crate::input::put_short_field;

/// A transport that takes and gives everything at once.
const SMOOTH: [u8; 8] = [255, 0, 0, 0, 255, 0, 0, 0];
/// Small chunks, `Pending` reads, writes and flushes, little room.
const CHOPPY: [u8; 8] = [
    7,
    0b0101_0101,
    0b0011_0011,
    3,
    13,
    0b0010_0100,
    0b1001_0010,
    16,
];

const HELLO: &[u8] = b"hello through an unbuffered stream";
const REPLY: &[u8] = b"and back, gathered from slices";
const UPDATED: &[u8] = b"after a key update";

fn header(knobs: [u8; 5], mode: [u8; 2], transport: [u8; 8]) -> Vec<u8> {
    [&knobs[..], &mode, &transport].concat()
}

fn op(out: &mut Vec<u8>, op: Op, arg: usize) {
    out.push(op as u8);
    out.push(arg as u8);
}

fn write(out: &mut Vec<u8>, side: usize, vectored: bool, data: &[u8]) {
    op(out, Op::Write, side);
    out.push(u8::from(vectored));
    put_short_field(out, data);
}

/// A write of `len` generated bytes.
fn write_generated(out: &mut Vec<u8>, side: usize, vectored: bool, len: usize) {
    op(out, Op::Write, side);
    out.push(2 | u8::from(vectored) | if len >= 65_536 { 4 } else { 0 });
    out.extend(((len % 65_536) as u16).to_be_bytes());
}

fn read(out: &mut Vec<u8>, side: usize, flags: u8, size: u8) {
    op(out, Op::Read, side);
    out.extend([flags, size]);
}

/// A handshake, data both ways through every kind of read and write, a key
/// update, and an orderly end.
fn exchange(out: &mut Vec<u8>) {
    for side in [CLIENT, SERVER] {
        op(out, Op::Accessors, side);
    }
    op(out, Op::Pump, 0);
    for side in [CLIENT, SERVER] {
        op(out, Op::Accessors, side);
    }
    write(out, CLIENT, false, HELLO);
    write(out, SERVER, true, REPLY);
    op(out, Op::Pump, 0);
    op(out, Op::KeyUpdate, SERVER);
    write(out, SERVER, false, UPDATED);
    op(out, Op::Pump, 3);
    write_generated(out, CLIENT, false, 300);
    op(out, Op::Flush, CLIENT);
    read(out, SERVER, 1, 7);
    read(out, SERVER, 0, 255);
    op(out, Op::Pump, 1);
    op(out, Op::TakeEarlyData, SERVER);
    op(out, Op::Shutdown, CLIENT);
    op(out, Op::Pump, 0);
    op(out, Op::Shutdown, SERVER);
    op(out, Op::Pump, 2);
    read(out, CLIENT, 0, 16);
    read(out, SERVER, 1, 16);
}

/// The creation modes of the exchange seeds: client, server.
const MODES: [[u8; 2]; 9] = [
    [0, 0],
    [1, 1],
    [2, 2],
    [3, 3],
    // Fallible futures; the streams end through `into_parts`.
    [0x24, 0x28],
    // A lazy acceptor's fallible future.
    [1, 0x0a],
    // A ClientHello the harness reads itself.
    [0, 5],
    // Buffered peers.
    [8, 0],
    [0, 4],
];

/// Every creation mode with a full exchange.
fn exchanges() -> Vec<Vec<u8>> {
    let mut seeds = Vec::new();
    // TLS 1.3 then TLS 1.2, smooth and choppy.
    for versions in [1u8, 2] {
        for mode in MODES {
            for transport in [SMOOTH, CHOPPY] {
                let mut s = header([versions, 0, 0, 0, 0], mode, transport);
                exchange(&mut s);
                seeds.push(s);
            }
        }
    }
    // Both versions offered: a lazily chosen TLS 1.2 configuration serves.
    // Identity record protection, undisturbed.
    for (versions, server) in [(0, 0x12), (1, 0x40)] {
        let mut s = header([versions, 0, 0, 0, 0], [0, server], SMOOTH);
        exchange(&mut s);
        seeds.push(s);
    }
    seeds
}

/// Bulk data: more than one write takes, records gathered from slices,
/// small fragments, a byte at a time.
fn bulk() -> Vec<Vec<u8>> {
    [(0, SMOOTH), (0, CHOPPY), (12, [1, 0, 0, 1, 1, 0, 0, 1])]
        .into_iter()
        .map(|(fragment, transport)| {
            let mut s = header([1, 0, 0, 0, fragment], [0, 0], transport);
            op(&mut s, Op::Pump, 0);
            write_generated(&mut s, CLIENT, false, 70_000);
            write_generated(&mut s, SERVER, true, 40_000);
            op(&mut s, Op::Pump, 2);
            write_generated(&mut s, CLIENT, true, 70_000);
            write_generated(&mut s, SERVER, false, 5000);
            op(&mut s, Op::Pump, 1);
            s
        })
        .collect()
}

/// Streams taken apart with plaintext unread, records unprocessed and
/// records unwritten; the connections go on by hand.
fn apart() -> Vec<Vec<u8>> {
    [1u8, 2]
        .into_iter()
        .map(|versions| {
            let mut s = header([versions, 0, 0, 0, 0], [0, 0], SMOOTH);
            op(&mut s, Op::Pump, 0);
            write(&mut s, CLIENT, false, b"first record");
            op(&mut s, Op::Flush, CLIENT);
            write(&mut s, CLIENT, false, b"second record");
            op(&mut s, Op::Flush, CLIENT);
            write(&mut s, SERVER, false, b"never read whole");
            op(&mut s, Op::Flush, SERVER);
            read(&mut s, SERVER, 0, 1);
            op(&mut s, Op::IntoParts, SERVER);
            read(&mut s, CLIENT, 1, 5);
            // The client's transport takes nothing: its record stays
            // unwritten.
            op(&mut s, Op::Throttle, CLIENT);
            s.extend([255, 0, 255, 0]);
            write(&mut s, CLIENT, true, b"left in the outgoing buffer");
            op(&mut s, Op::IntoParts, CLIENT);
            op(&mut s, Op::Pump, 0);
            s
        })
        .collect()
}

/// 0-RTT: a first connection with a buffered client leaves a ticket, the
/// second writes early, to an acceptor and to a lazy acceptor. Last, an
/// unbuffered client that resumes and sends no 0-RTT data.
fn early() -> Vec<Vec<u8>> {
    let mut seeds = Vec::new();
    for (client, server) in [(0x18u8, 0u8), (0x18, 3), (1, 1)] {
        let mut s = header([0x41, 0, 0, 0, 0], [client, server], SMOOTH);
        op(&mut s, Op::Pump, 0);
        write(&mut s, SERVER, false, b"ticket");
        op(&mut s, Op::Pump, 0);
        op(&mut s, Op::Reconnect, 0);
        s.extend([client, server | 0x20]);
        // The buffered connect future returns at once, before the
        // handshake; the unbuffered one waits, and this write is not made.
        op(&mut s, Op::Poll, CLIENT);
        write(&mut s, CLIENT, false, b"early request");
        op(&mut s, Op::Pump, 0);
        op(&mut s, Op::Accessors, SERVER);
        op(&mut s, Op::TakeEarlyData, SERVER);
        write(&mut s, CLIENT, true, b"later");
        op(&mut s, Op::Pump, 0);
        seeds.push(s);
    }
    seeds
}

/// Post-handshake authentication while the client's transport takes
/// nothing: its answer waits in the stream until the transport opens.
fn answers() -> Vec<u8> {
    let mut s = header([1, 3, 0, 0, 0], [0, 0], SMOOTH);
    op(&mut s, Op::Pump, 0);
    op(&mut s, Op::Throttle, CLIENT);
    s.extend([255, 0, 255, 0]);
    op(&mut s, Op::RequestAuth, SERVER);
    op(&mut s, Op::Flush, SERVER);
    read(&mut s, CLIENT, 0, 16);
    read(&mut s, CLIENT, 1, 16);
    op(&mut s, Op::Throttle, CLIENT);
    s.extend([9, 0, 0b0101_0101, 1]);
    write(&mut s, SERVER, false, b"authenticated");
    op(&mut s, Op::Pump, 0);
    s
}

/// A record as the identity transform protects it: the content, then its
/// type.
fn forged_record(content_type: u8, content: &[u8]) -> Vec<u8> {
    let mut record = vec![0x17, 3, 3, 0, content.len() as u8 + 1];
    record.extend_from_slice(content);
    record.push(content_type);
    record
}

/// Records written on the wire under identity record protection.
fn forged() -> Vec<Vec<u8>> {
    let mut seeds = Vec::new();
    // KeyUpdate requests, one per transport read, to a client whose
    // transport takes nothing: its answers pile up until reads wait for
    // them; then the transport opens. Data now and then renews the budget
    // of requests.
    let mut s = header([1, 0, 0, 0, 0], [0, 0x40], SMOOTH);
    op(&mut s, Op::Pump, 0);
    op(&mut s, Op::Throttle, CLIENT);
    s.extend([255, 0, 255, 0]);
    op(&mut s, Op::Throttle, SERVER);
    s.extend([11, 0, 0, 0]);
    let mut burst = Vec::new();
    for _ in 0..2 {
        for _ in 0..8 {
            burst.extend(forged_record(0x16, &[24, 0, 0, 1, 1]));
        }
        burst.extend(forged_record(0x17, b"forge"));
    }
    for _ in 0..4 {
        op(&mut s, Op::Inject, SERVER);
        s.push(31);
        put_short_field(&mut s, &burst);
        read(&mut s, CLIENT, 2, 255);
    }
    op(&mut s, Op::Throttle, CLIENT);
    s.extend([255, 0, 0, 0]);
    read(&mut s, CLIENT, 2, 255);
    op(&mut s, Op::Pump, 0);
    seeds.push(s);

    // Data, then a close_notify or a fatal alert the peer never sent.
    for alert in [[1u8, 0], [2, 40]] {
        let mut s = header([1, 0, 0, 0, 0], [0, 0x40], SMOOTH);
        op(&mut s, Op::Pump, 0);
        op(&mut s, Op::Inject, CLIENT);
        s.push(0);
        put_short_field(
            &mut s,
            &[forged_record(0x17, b"forge"), forged_record(0x15, &alert)].concat(),
        );
        for flags in [0, 1, 0, 1] {
            read(&mut s, SERVER, flags, 16);
        }
        write(&mut s, SERVER, false, b"after the alert");
        op(&mut s, Op::Pump, 0);
        seeds.push(s);
    }
    seeds
}

/// Handshakes that are refused before or after the ClientHello.
fn refusals() -> Vec<Vec<u8>> {
    let mut seeds = Vec::new();
    // A lazy acceptor refusing a plain-text request, then giving the
    // transport back; and one giving it back while it waits.
    let mut s = header([1, 0, 0, 0, 0], [0, 2], SMOOTH);
    op(&mut s, Op::Inject, CLIENT);
    s.push(0);
    put_short_field(&mut s, b"GET / HTTP/1.1\r\n\r\n");
    op(&mut s, Op::Poll, SERVER);
    op(&mut s, Op::Accessors, SERVER);
    op(&mut s, Op::Poll, SERVER);
    op(&mut s, Op::TakeIo, SERVER);
    seeds.push(s);
    let mut s = header([1, 0, 0, 0, 0], [0, 3], CHOPPY);
    op(&mut s, Op::Poll, SERVER);
    op(&mut s, Op::TakeIo, SERVER);
    op(&mut s, Op::Pump, 0);
    seeds.push(s);
    // A lazily chosen configuration that cannot serve the ClientHello: its
    // alert is sent before the future fails. Configurations the connection
    // refuses (a fragment size no record may have).
    for (knobs, mode) in [
        ([1u8, 0, 0, 0, 0], [0u8, 0x12]),
        ([1, 0, 0, 0, 0], [4, 0x1b]),
        ([1, 0, 0, 0, 1], [0, 0]),
        ([2, 0, 0, 0, 1], [4, 9]),
    ] {
        let mut s = header(knobs, mode, CHOPPY);
        for side in [CLIENT, SERVER] {
            op(&mut s, Op::Accessors, side);
        }
        op(&mut s, Op::Pump, 0);
        seeds.push(s);
    }
    seeds
}

/// Damaged handshakes, an early end of file, failing transports.
fn broken_handshakes() -> Vec<Vec<u8>> {
    let mut seeds = Vec::new();
    for (lane, damage, kind) in [
        (CLIENT, Op::Damage, 0),
        (SERVER, Op::Damage, 0),
        (CLIENT, Op::Break, 0),
        (SERVER, Op::Break, 1),
        (CLIENT, Op::Break, 2),
        (SERVER, Op::Break, 3),
    ] {
        for mode in [[4u8, 8u8], [0, 2]] {
            let mut s = header([1, 0, 0, 0, 0], mode, SMOOTH);
            // Each side's first flight is hit while it is in flight.
            for side in [CLIENT, SERVER] {
                // A lazy acceptor writes at its second poll.
                op(&mut s, Op::Poll, side);
                op(&mut s, Op::Poll, side);
                if side == lane {
                    op(&mut s, damage, lane);
                    if matches!(damage, Op::Damage) {
                        s.extend([0, 40, 0x55]);
                    } else {
                        s.push(kind);
                    }
                }
            }
            op(&mut s, Op::Pump, 0);
            read(&mut s, CLIENT, 0, 16);
            seeds.push(s);
        }
    }
    seeds
}

/// The same after the handshake, in both directions and versions: the
/// failure is final for reads and writes, and a shutdown still works.
fn broken_streams() -> Vec<Vec<u8>> {
    let mut seeds = Vec::new();
    for versions in [1u8, 2] {
        for (lane, damage, kind) in [
            (CLIENT, Op::Damage, 0),
            (SERVER, Op::Damage, 0),
            (SERVER, Op::Inject, 0),
            (SERVER, Op::Break, 0),
            (CLIENT, Op::Break, 1),
            (CLIENT, Op::Break, 2),
            (SERVER, Op::Break, 3),
        ] {
            let mut s = header([versions, 0, 0, 0, 0], [0, 0], SMOOTH);
            op(&mut s, Op::Pump, 0);
            write(&mut s, lane, false, b"a record that will not arrive whole");
            op(&mut s, Op::Flush, lane);
            op(&mut s, damage, lane);
            match damage {
                Op::Damage => s.extend([0, 9, 0x80]),
                Op::Inject => {
                    s.push(0);
                    put_short_field(
                        &mut s,
                        &[&[0x17, 3, 3, 0, 0x20][..], &[0xaa; 0x20]].concat(),
                    );
                }
                _ => s.push(kind),
            }
            for side in [1 - lane, lane] {
                read(&mut s, side, 0, 5);
                read(&mut s, side, 1, 16);
                read(&mut s, side, 0, 16);
                write(&mut s, side, false, b"after the failure");
                op(&mut s, Op::Flush, side);
                op(&mut s, Op::Accessors, side);
            }
            op(&mut s, Op::Pump, 0);
            op(&mut s, Op::Shutdown, 1 - lane);
            op(&mut s, Op::IntoParts, lane);
            op(&mut s, Op::Pump, 0);
            seeds.push(s);
        }
    }
    seeds
}

/// Seeds: every creation mode with a full exchange, bulk data, streams
/// taken apart, 0-RTT data a server accepts, answers that wait for the
/// transport, forged records, refusals, and damaged, cut and failing
/// transports.
pub fn seeds() -> Vec<Vec<u8>> {
    let mut seeds = exchanges();
    seeds.extend(bulk());
    seeds.extend(apart());
    seeds.extend(early());
    seeds.push(answers());
    seeds.extend(forged());
    seeds.extend(refusals());
    seeds.extend(broken_handshakes());
    seeds.extend(broken_streams());
    seeds
}

#[cfg(test)]
mod tests {
    use super::super::play;
    use super::super::world::{Side, World};
    use super::*;

    fn played(seed: &[u8]) -> World {
        play(seed).expect("configurations")
    }

    /// The seeds do what they are meant to, so the harness's checks run on
    /// real traffic.
    #[test]
    fn seeds_exchange_data() {
        let (mut waiting, mut fallible) = ([0; 2], [0; 2]);
        for (i, seed) in exchanges().iter().enumerate() {
            let world = played(seed);
            for side in [CLIENT, SERVER] {
                waiting[side] += world.stats.waiting[side];
                fallible[side] += world.stats.fallible[side];
            }
            assert!(world.received[CLIENT].ends_with(UPDATED), "seed {i}");
            assert!(world.received[CLIENT].starts_with(REPLY), "seed {i}");
            assert!(world.received[SERVER].starts_with(HELLO), "seed {i}");
            assert_eq!(world.received[SERVER].len(), HELLO.len() + 300, "seed {i}");
            assert_eq!(world.stats.handshakes, 2, "seed {i}");
            // Every pump found everything delivered, and both streams ended.
            assert_eq!(world.stats.delivered, 6, "seed {i}");
            assert!(
                world.notes[CLIENT].eof && world.notes[SERVER].eof,
                "seed {i}"
            );
            assert!(!world.notes[CLIENT].errored && !world.notes[SERVER].errored);
        }
        // The accessors and `into_fallible` of both handshake futures ran.
        assert!(waiting.iter().chain(&fallible).all(|calls| *calls > 0));
    }

    #[test]
    fn seeds_move_bulk_data() {
        for seed in bulk() {
            let world = played(&seed);
            // One write takes four records' worth, a vectored write of
            // small slices one record's worth.
            assert_eq!(world.sent[CLIENT].len(), 65_536 + 17_500);
            assert_eq!(world.sent[SERVER].len(), 16_384 + 5000);
            assert_eq!(world.received[SERVER].len(), world.sent[CLIENT].len());
            assert_eq!(world.stats.delivered, 3);
        }
    }

    #[test]
    fn seeds_take_streams_apart() {
        for seed in apart() {
            let world = played(&seed);
            assert_eq!(world.stats.manual, 2);
            assert!(world.stats.unsent > 27, "no record was left unwritten");
            assert!(matches!(world.sides[CLIENT], Side::Manual(_)));
            assert_eq!(
                world.received[SERVER],
                b"first recordsecond recordleft in the outgoing buffer"
            );
            assert_eq!(world.received[CLIENT], b"never read whole");
            assert_eq!(world.stats.delivered, 2);
        }
    }

    #[test]
    fn seeds_send_early_data_to_an_unbuffered_server() {
        let seeds = early();
        for seed in &seeds[..2] {
            let world = played(seed);
            assert!(world.early_attempted);
            assert_eq!(world.early, b"early request");
            assert_eq!(world.received[SERVER], b"later");
            assert_eq!(world.stats.delivered, 4);
        }
        let world = played(&seeds[2]);
        assert!(!world.early_attempted && world.early.is_empty());
        assert_eq!(world.received[SERVER], b"later");
        assert_eq!(world.stats.handshakes, 4);
    }

    #[test]
    fn seeds_leave_answers_waiting() {
        let world = played(&answers());
        assert!(world.stats.unsent > 256, "{}", world.stats.unsent);
        assert!(world.lenient && !world.notes[CLIENT].errored);
        assert_eq!(world.received[CLIENT], b"authenticated");
        assert_eq!(world.stats.delivered, 2);
    }

    #[test]
    fn seeds_forge_records() {
        let seeds = forged();
        // The answers to the forged requests waited in the stream, up to
        // the point where reads stop taking input, and no further.
        let world = played(&seeds[0]);
        let unsent = world.stats.unsent;
        assert!(
            (16 * 1024 + 1..16 * 1024 + 64).contains(&unsent),
            "{unsent}"
        );
        assert!(!world.notes[CLIENT].errored && !world.notes[SERVER].errored);
        assert_eq!(world.received[CLIENT].len(), 4 * 32 * 2 * 5);
        assert_eq!(world.wire.borrow().lanes[SERVER].bytes.len(), 0);

        // A forged close_notify ends the stream, a forged alert fails it.
        let world = played(&seeds[1]);
        assert_eq!(world.received[SERVER], b"forge");
        assert!(world.notes[SERVER].eof && !world.notes[SERVER].errored);
        assert_eq!(world.sent[SERVER], b"after the alert");
        let world = played(&seeds[2]);
        assert_eq!(world.received[SERVER], b"forge");
        assert!(world.notes[SERVER].tls_failed && world.sent[SERVER].is_empty());
        assert!(world.stats.sticky >= 2);
    }

    #[test]
    fn seeds_are_refused_and_fail() {
        // The lazy acceptor refused, with an alert.
        let seeds = refusals();
        let world = played(&seeds[0]);
        assert!(matches!(world.sides[SERVER], Side::Gone));
        assert!(
            !world.wire.borrow().lanes[SERVER].bytes.is_empty(),
            "no alert"
        );
        // A configuration that cannot serve the hello, or that the
        // connection refuses: both sides fail.
        for seed in &seeds[2..] {
            let world = played(seed);
            assert!(world.sides.iter().all(|side| matches!(side, Side::Gone)));
            assert!(world.notes[CLIENT].errored && world.notes[SERVER].errored);
        }
        for (i, seed) in broken_handshakes().iter().enumerate() {
            let world = played(seed);
            let errored = world.notes[CLIENT].errored || world.notes[SERVER].errored;
            assert!(errored, "seed {i}");
        }
        // Failures after the handshake stay failures.
        for (i, seed) in broken_streams().iter().enumerate() {
            let world = played(seed);
            assert_eq!(world.stats.handshakes, 2, "seed {i}");
            // A failing transport fails the client's writes or reads;
            // everything else fails a reader, for good.
            if matches!(i % 7, 4..=6) {
                assert!(world.notes[CLIENT].errored, "seed {i}");
            } else {
                assert!(world.stats.sticky > 0, "seed {i}");
            }
        }
    }
}

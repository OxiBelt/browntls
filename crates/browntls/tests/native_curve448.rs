/// The client offers only `offer` and records the schemes it verifies.
fn recording_server_verifier(
    chain: &Ed448Chain,
    offer: &[SignatureScheme],
) -> Arc<SchemeRecordingServerVerifier> {
    SchemeRecordingServerVerifier::new(webpki_server_verifier(chain), offer)
}

fn webpki_client_verifier(
    chain: &Ed448Chain,
) -> Arc<dyn browntls::server::danger::ClientCertVerifier> {
    WebPkiClientVerifier::builder_with_provider(chain.roots(), provider())
        .build()
        .unwrap()
}

#[test]
fn ed448_chains_authenticate_server_and_client() {
    init_logging();
    let server_chain = Ed448Chain::server();
    let client_chain = Ed448Chain::client();
    let all_schemes = prov::SUPPORTED_SIG_ALGS.supported_schemes();
    assert!(all_schemes.contains(&SignatureScheme::ED448));
    for v in VERSIONS {
        let server_verifier = recording_server_verifier(&server_chain, &all_schemes);
        let client_verifier =
            SchemeRecordingClientVerifier::new(webpki_client_verifier(&client_chain), &all_schemes);
        let client = client_for(v, provider(), server_verifier.clone())
            .with_client_auth_cert(client_chain.cert_chain(), client_chain.private_key())
            .unwrap();
        let server = ServerConfig::builder_with_provider(provider())
            .with_safe_default_protocol_versions()
            .unwrap()
            .with_client_cert_verifier(client_verifier.clone())
            .with_single_cert(server_chain.cert_chain(), server_chain.private_key())
            .unwrap();
        let (mut client, mut server) = connect(client, server);
        do_handshake(&mut client, &mut server).unwrap_or_else(|e| panic!("{v:?}: {e}"));
        assert_eq!(client.protocol_version(), Some(v));
        assert_eq!(server_verifier.seen(), [SignatureScheme::ED448], "{v:?}");
        assert_eq!(client_verifier.seen(), [SignatureScheme::ED448], "{v:?}");
        assert_eq!(
            client.peer_certificates().unwrap(),
            server_chain.cert_chain()
        );
        assert_eq!(
            server.peer_certificates().unwrap(),
            client_chain.cert_chain()
        );
        if v == ProtocolVersion::TLSv1_2 {
            // Ed448 keys use the ECDHE_ECDSA suites (RFC 8422 §5.1.3).
            let suite = format!("{:?}", client.negotiated_cipher_suite().unwrap().suite());
            assert!(suite.contains("ECDHE_ECDSA"), "{suite}");
        }
        round_trip(&mut client, &mut server);
    }
}


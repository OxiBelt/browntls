/// Wraps a signing key so that every signature has one bit flipped.
#[derive(Debug)]
struct Tampering(Arc<dyn SigningKey>);

#[derive(Debug)]
struct TamperingSigner(Box<dyn Signer>);

impl SigningKey for Tampering {
    fn choose_scheme(&self, offered: &[SignatureScheme]) -> Option<Box<dyn Signer>> {
        self.0
            .choose_scheme(offered)
            .map(|s| Box::new(TamperingSigner(s)) as Box<dyn Signer>)
    }

    fn public_key(&self) -> Option<browntls::pki_types::SubjectPublicKeyInfoDer<'_>> {
        self.0.public_key()
    }

    fn algorithm(&self) -> SignatureAlgorithm {
        self.0.algorithm()
    }
}

impl Signer for TamperingSigner {
    fn sign(&self, message: &[u8]) -> Result<Vec<u8>, Error> {
        let mut sig = self.0.sign(message)?;
        sig[10] ^= 0x01;
        Ok(sig)
    }

    fn scheme(&self) -> SignatureScheme {
        self.0.scheme()
    }
}

#[derive(Debug)]
struct ClientKey(Arc<CertifiedKey>);

impl browntls::client::ResolvesClientCert for ClientKey {
    fn resolve(
        &self,
        _root_hint_subjects: &[&[u8]],
        _sigschemes: &[SignatureScheme],
    ) -> Option<Arc<CertifiedKey>> {
        Some(self.0.clone())
    }

    fn has_certs(&self) -> bool {
        true
    }
}

#[test]
fn tampered_ed448_handshake_signatures_are_rejected() {
    init_logging();
    let server_chain = Ed448Chain::server();
    let client_chain = Ed448Chain::client();
    let bad_sig = Error::InvalidCertificate(CertificateError::BadSignature);
    for v in VERSIONS {
        // Server CertificateVerify / ServerKeyExchange signature.
        let client =
            client_for(v, provider(), webpki_server_verifier(&server_chain)).with_no_client_auth();
        let server = ServerConfig::builder_with_provider(provider())
            .with_safe_default_protocol_versions()
            .unwrap()
            .with_no_client_auth()
            .with_cert_resolver(Arc::new(SingleCertAndKey::from(
                server_chain.certified_key(|k| Arc::new(Tampering(k))),
            )));
        let (mut client, mut server) = connect(client, server);
        let (client_res, _) = do_handshake_until_error(&mut client, &mut server);
        assert_eq!(client_res, Err(bad_sig.clone()), "{v:?} server signature");

        // Client CertificateVerify signature.
        let client = client_for(v, provider(), webpki_server_verifier(&server_chain))
            .with_client_cert_resolver(Arc::new(ClientKey(
                client_chain.certified_key(|k| Arc::new(Tampering(k))),
            )));
        let server = ServerConfig::builder_with_provider(provider())
            .with_safe_default_protocol_versions()
            .unwrap()
            .with_client_cert_verifier(webpki_client_verifier(&client_chain))
            .with_single_cert(server_chain.cert_chain(), server_chain.private_key())
            .unwrap();
        let (mut client, mut server) = connect(client, server);
        let (_, server_res) = do_handshake_until_error(&mut client, &mut server);
        assert_eq!(server_res, Err(bad_sig.clone()), "{v:?} client signature");
    }
}

#[test]
fn tampered_ed448_certificate_signature_is_rejected() {
    init_logging();
    let chain = Ed448Chain::server();
    let mut der = chain.end_entity.as_ref().to_vec();
    let last = der.len() - 1;
    der[last - 20] ^= 0x01; // inside the 114-byte signatureValue
    let tampered = vec![CertificateDer::from(der), chain.ca.clone()];
    for v in VERSIONS {
        let client =
            client_for(v, provider(), webpki_server_verifier(&chain)).with_no_client_auth();
        let server = ServerConfig::builder_with_provider(provider())
            .with_safe_default_protocol_versions()
            .unwrap()
            .with_no_client_auth()
            .with_single_cert(tampered.clone(), chain.private_key())
            .unwrap();
        let (mut client, mut server) = connect(client, server);
        let (client_res, _) = do_handshake_until_error(&mut client, &mut server);
        assert_eq!(
            client_res,
            Err(Error::InvalidCertificate(CertificateError::BadSignature)),
            "{v:?}"
        );
    }
}

#[test]
fn ed448_requires_the_peer_to_offer_it() {
    init_logging();
    let chain = Ed448Chain::server();
    let without_ed448: Vec<SignatureScheme> = prov::SUPPORTED_SIG_ALGS
        .supported_schemes()
        .into_iter()
        .filter(|s| *s != SignatureScheme::ED448)
        .collect();
    for v in VERSIONS {
        let client = client_for(
            v,
            provider(),
            recording_server_verifier(&chain, &without_ed448),
        )
        .with_no_client_auth();
        let (mut client, mut server) = connect(
            client,
            ServerConfig::builder_with_provider(provider())
                .with_safe_default_protocol_versions()
                .unwrap()
                .with_no_client_auth()
                .with_single_cert(chain.cert_chain(), chain.private_key())
                .unwrap(),
        );
        let (client_res, server_res) = do_handshake_until_error(&mut client, &mut server);
        assert_eq!(
            server_res,
            Err(Error::PeerIncompatible(
                PeerIncompatible::NoSignatureSchemesInCommon
            )),
            "{v:?}"
        );
        assert_eq!(
            client_res,
            Err(Error::AlertReceived(AlertDescription::HandshakeFailure)),
            "{v:?}"
        );
    }
}


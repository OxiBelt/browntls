/// Runs `kernel` over all four instances, `vl` at a time.
///
/// # Safety
///
/// The extensions required by `kernel` must be available.
unsafe fn run(s: &mut StateX4, kernel: unsafe fn(*mut u64, usize) -> usize) {
    let base = s.as_mut_ptr().cast::<u64>();
    let mut j = 0;
    while j < 4 {
        // SAFETY: the caller guarantees the extensions; `base + j` is lane 0
        // of instance `j`, and lane `i` of instances `j..4` occupies the
        // `4 - j` consecutive `u64`s at offset `4 * i + j` of `s`.
        let vl = unsafe { kernel(base.wrapping_add(j), 4 - j) };
        if vl == 0 {
            break;
        }
        j += vl;
    }
    if j < 4 {
        // Unreachable for VLEN >= 128; kept so an unexpected `vl == 0` can
        // never leave instances unpermuted.
        for k in j..4 {
            let mut one: [u64; 25] = core::array::from_fn(|i| s[i][k]);
            soft::keccak_f1600(&mut one);
            for (lane, v) in s.iter_mut().zip(one) {
                lane[k] = v;
            }
        }
    }
}

/// Four-way permutation with base RVV 1.0.
pub(super) fn keccak_f1600_x4_rvv(s: &mut StateX4) {
    if rvv_available(cpu::features()) {
        // SAFETY: RVV 1.0 was detected at run time (or asserted at build
        // time).
        unsafe { run(s, kernel_rvv) }
    } else {
        soft::keccak_f1600_x4(s);
    }
}


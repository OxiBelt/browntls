//! riscv64 Keccak-f\[1600\] backends: scalar Zbb and VLEN-agnostic RVV
//! four-way.
//!
//! RVV intrinsics are not available on stable Rust, so the vector kernel is
//! inline assembly assembled with `.option arch, +v`. Each instance's lane `i`
//! is one e64 element; each `vsetvli` with AVL = remaining instances grants
//! some `vl` between 1 and `min(AVL, VLEN/64)` (RVV may grant fewer than AVL
//! when AVL < 2 * VLMAX), and the wrapper loops until all four instances are
//! done.
//!
//! Register allocation: lane `i` lives in `v{i}` (`v0`..`v24`), `v25`..`v31`
//! are temporaries. One round (θ, ρ+π as a register cycle, χ row by row, ι)
//! is emitted once and executed 24 times. The round body was generated by a
//! small script from the ρ/π tables (the same tables as `soft`) in two
//! flavours: base RVV 1.0 (`vsll`/`vsrl`/`vor` rotates and `vxor`+`vand` for
//! `AND-NOT`) and Zvkb (`vror.vi`, `vandn.vv`).
#![allow(unsafe_code)]

use core::arch::asm;

use super::{RC, StateX4, permute, soft};
use crate::cpu::{self, Features};

pub(super) fn zbb_available(f: Features) -> bool {
    f.rv_zbb()
}

pub(super) fn rvv_available(f: Features) -> bool {
    f.rv_v()
}

pub(super) fn rvv_zvkb_available(f: Features) -> bool {
    f.rv_v() && f.rv_zvkb()
}

#[target_feature(enable = "zbb")]
fn permute_zbb(state: &mut [u64; 25]) {
    permute(state);
}

/// Scalar permutation compiled with Zbb (`RORI`, `ANDN`).
pub(super) fn keccak_f1600_zbb(state: &mut [u64; 25]) {
    if zbb_available(cpu::features()) {
        // SAFETY: Zbb was detected at run time (or asserted at build time).
        unsafe { permute_zbb(state) }
    } else {
        soft::keccak_f1600(state);
    }
}


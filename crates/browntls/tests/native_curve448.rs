/// DER helpers over `browntls_crypto::der::Writer`.
mod der {
    use super::{Writer, header_len};

    pub(super) fn tlv(tag: u8, content: &[u8]) -> Vec<u8> {
        let mut out = vec![0u8; header_len(content.len()) + content.len()];
        let len = {
            let mut w = Writer::new(&mut out);
            w.tlv(tag, content).unwrap();
            w.len()
        };
        out.truncate(len);
        out
    }

    pub(super) fn seq(parts: &[&[u8]]) -> Vec<u8> {
        tlv(0x30, &parts.concat())
    }

    pub(super) fn uint(magnitude: &[u8]) -> Vec<u8> {
        let mut out = vec![0u8; Writer::positive_integer_len(magnitude)];
        let len = {
            let mut w = Writer::new(&mut out);
            w.positive_integer(magnitude).unwrap();
            w.len()
        };
        out.truncate(len);
        out
    }

    pub(super) fn oid(contents: &[u8]) -> Vec<u8> {
        tlv(0x06, contents)
    }
}

/// `AlgorithmIdentifier { id-Ed448 }` without parameters (RFC 8410 §3).
const ALG_ED448: &[u8] = &[0x30, 0x05, 0x06, 0x03, 0x2b, 0x65, 0x71];
const OID_CN: &[u8] = &[0x55, 0x04, 0x03];
const OID_BASIC_CONSTRAINTS: &[u8] = &[0x55, 0x1d, 0x13];
const OID_KEY_USAGE: &[u8] = &[0x55, 0x1d, 0x0f];
const OID_EXT_KEY_USAGE: &[u8] = &[0x55, 0x1d, 0x25];
const OID_SUBJECT_ALT_NAME: &[u8] = &[0x55, 0x1d, 0x11];
const OID_KP_SERVER_AUTH: &[u8] = &[0x2b, 0x06, 0x01, 0x05, 0x05, 0x07, 0x03, 0x01];
const OID_KP_CLIENT_AUTH: &[u8] = &[0x2b, 0x06, 0x01, 0x05, 0x05, 0x07, 0x03, 0x02];

fn name(cn: &str) -> Vec<u8> {
    let atv = der::seq(&[&der::oid(OID_CN), &der::tlv(0x0c, cn.as_bytes())]);
    der::seq(&[&der::tlv(0x31, &atv)])
}

fn extension(oid: &[u8], critical: bool, value: &[u8]) -> Vec<u8> {
    let critical: &[u8] = if critical { &[0x01, 0x01, 0xff] } else { &[] };
    der::seq(&[&der::oid(oid), critical, &der::tlv(0x04, value)])
}

/// An Ed448 key generated by `browntls-crypto` and loaded by the native
/// provider's key loader.
struct Ed448Key {
    pkcs8: Vec<u8>,
    key: Arc<dyn SigningKey>,
    spki: Vec<u8>,
}

impl Ed448Key {
    fn generate() -> Self {
        let key = ed448::SigningKey::generate(&OsRng).unwrap();
        let pkcs8 = key.to_pkcs8_der().to_vec();
        let loaded = prov::KEY_PROVIDER
            .load_private_key(PrivateKeyDer::Pkcs8(PrivatePkcs8KeyDer::from(
                pkcs8.clone(),
            )))
            .expect("the native provider loads Ed448 PKCS #8 keys");
        assert_eq!(loaded.algorithm(), SignatureAlgorithm::ED448);
        let spki = loaded.public_key().unwrap().as_ref().to_vec();
        assert_eq!(
            &spki[..12],
            &[
                0x30, 0x43, 0x30, 0x05, 0x06, 0x03, 0x2b, 0x65, 0x71, 0x03, 0x3a, 0x00
            ]
        );
        assert_eq!(&spki[12..], key.verifying_key().as_bytes());
        Self {
            pkcs8,
            key: loaded,
            spki,
        }
    }

    /// Signs `tbs` with the provider's Ed448 signer.
    fn sign(&self, tbs: &[u8]) -> Vec<u8> {
        let signer = self.key.choose_scheme(&[SignatureScheme::ED448]).unwrap();
        assert_eq!(signer.scheme(), SignatureScheme::ED448);
        signer.sign(tbs).unwrap()
    }
}

/// Builds an X.509 v3 certificate for `subject_key` signed by `issuer_key`
/// with Ed448 (RFC 5280 §4.1, RFC 8410 §6).
fn certificate(
    issuer: &str,
    issuer_key: &Ed448Key,
    subject: &str,
    subject_key: &Ed448Key,
    extensions: &[Vec<u8>],
) -> Vec<u8> {
    let mut serial = [0u8; 16];
    OsRng.fill(&mut serial).unwrap();
    serial[0] &= 0x7f;
    serial[0] |= 0x01;
    let exts: Vec<&[u8]> = extensions.iter().map(Vec::as_slice).collect();
    let tbs = der::seq(&[
        &der::tlv(0xa0, &der::uint(&[2])),
        &der::uint(&serial),
        ALG_ED448,
        &name(issuer),
        &der::seq(&[
            &der::tlv(0x17, b"200101000000Z"),
            &der::tlv(0x18, b"20991231235959Z"),
        ]),
        &name(subject),
        &subject_key.spki,
        &der::tlv(0xa3, &der::seq(&exts)),
    ]);
    let mut bits = vec![0u8];
    bits.extend_from_slice(&issuer_key.sign(&tbs));
    assert_eq!(bits.len(), 1 + ed448::SIGNATURE_LEN);
    der::seq(&[&tbs, ALG_ED448, &der::tlv(0x03, &bits)])
}

/// An Ed448 CA and an Ed448 end entity issued by it.
struct Ed448Chain {
    ca: CertificateDer<'static>,
    end_entity: CertificateDer<'static>,
    ee_key: Ed448Key,
}

impl Ed448Chain {
    fn generate(names: &[&str], eku: &[u8]) -> Self {
        let ca_key = Ed448Key::generate();
        let ee_key = Ed448Key::generate();
        let ca_name = "browntls test CA (Ed448)";
        let ca = certificate(
            ca_name,
            &ca_key,
            ca_name,
            &ca_key,
            &[
                extension(
                    OID_BASIC_CONSTRAINTS,
                    true,
                    &der::seq(&[&[0x01, 0x01, 0xff]]),
                ),
                // keyCertSign, cRLSign
                extension(OID_KEY_USAGE, true, &[0x03, 0x02, 0x01, 0x06]),
            ],
        );
        let sans: Vec<Vec<u8>> = names.iter().map(|n| der::tlv(0x82, n.as_bytes())).collect();
        let sans: Vec<&[u8]> = sans.iter().map(Vec::as_slice).collect();
        let end_entity = certificate(
            ca_name,
            &ca_key,
            names[0],
            &ee_key,
            &[
                extension(OID_BASIC_CONSTRAINTS, true, &der::seq(&[])),
                // digitalSignature
                extension(OID_KEY_USAGE, true, &[0x03, 0x02, 0x07, 0x80]),
                extension(OID_EXT_KEY_USAGE, false, &der::seq(&[&der::oid(eku)])),
                extension(OID_SUBJECT_ALT_NAME, false, &der::seq(&sans)),
            ],
        );
        Self {
            ca: CertificateDer::from(ca),
            end_entity: CertificateDer::from(end_entity),
            ee_key,
        }
    }

    fn server() -> Self {
        Self::generate(&["localhost", "testserver.example"], OID_KP_SERVER_AUTH)
    }

    fn client() -> Self {
        Self::generate(&["client.example"], OID_KP_CLIENT_AUTH)
    }

    fn cert_chain(&self) -> Vec<CertificateDer<'static>> {
        vec![self.end_entity.clone(), self.ca.clone()]
    }

    fn private_key(&self) -> PrivateKeyDer<'static> {
        PrivateKeyDer::Pkcs8(PrivatePkcs8KeyDer::from(self.ee_key.pkcs8.clone()))
    }

    fn roots(&self) -> Arc<RootCertStore> {
        let mut roots = RootCertStore::empty();
        roots.add(self.ca.clone()).unwrap();
        Arc::new(roots)
    }

    /// The chain served through a signing key wrapped by `wrap`.
    fn certified_key(
        &self,
        wrap: impl FnOnce(Arc<dyn SigningKey>) -> Arc<dyn SigningKey>,
    ) -> Arc<CertifiedKey> {
        Arc::new(CertifiedKey::new(
            self.cert_chain(),
            wrap(self.ee_key.key.clone()),
        ))
    }
}

// --------------------------------------------------------------- configs

fn provider_with_groups(groups: &[&'static dyn SupportedKxGroup]) -> Arc<CryptoProvider> {
    let mut provider = prov::default_provider();
    provider.kx_groups = groups.to_vec();
    Arc::new(provider)
}

fn webpki_server_verifier(chain: &Ed448Chain) -> Arc<WebPkiServerVerifier> {
    WebPkiServerVerifier::builder_with_provider(chain.roots(), provider())
        .build()
        .unwrap()
}

fn client_for(
    v: ProtocolVersion,
    provider: Arc<CryptoProvider>,
    verifier: Arc<dyn browntls::client::danger::ServerCertVerifier>,
) -> browntls::ConfigBuilder<ClientConfig, browntls::client::WantsClientCert> {
    ClientConfig::builder_with_provider(provider)
        .with_protocol_versions(versions(v))
        .unwrap()
        .dangerous()
        .with_custom_certificate_verifier(verifier)
}

fn connect(client: ClientConfig, server: ServerConfig) -> (ClientConnection, ServerConnection) {
    (
        ClientConnection::new(Arc::new(client), server_name()).unwrap(),
        ServerConnection::new(Arc::new(server)).unwrap(),
    )
}

fn round_trip(client: &mut ClientConnection, server: &mut ServerConnection) {
    assert_eq!(send_and_receive(client, server, b"ping"), b"ping");
    assert_eq!(send_and_receive(server, client, b"pong"), b"pong");
}

fn x448() -> &'static dyn SupportedKxGroup {
    prov::kx_group::X448
}

